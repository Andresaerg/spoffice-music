package models

// GET /api/v1/search.
type InvidiousSearchParams struct {
	Query    string `json:"q"`
	Page     int32  `json:"page,omitempty"`
	Sort     string `json:"sort,omitempty"`
	Date     string `json:"date,omitempty"`
	Duration string `json:"duration,omitempty"`
	Type     string `json:"type,omitempty"`
	Features string `json:"features,omitempty"`
	Region   string `json:"region,omitempty"`
}

type InvidiousSearchResultItem struct {
	Type            string               `json:"type"`
	Title           string               `json:"title"`
	VideoID         string               `json:"videoId"`
	Author          string               `json:"author"`
	AuthorID        string               `json:"authorId"`
	AuthorURL       string               `json:"authorUrl"`
	VideoThumbnails []InvidiousThumbnail `json:"videoThumbnails"`
	Description     string               `json:"description"`
	DescriptionHTML string               `json:"descriptionHtml"`
	ViewCount       int64                `json:"viewCount"`
	Published       int64                `json:"published"`
	PublishedText   string               `json:"publishedText"`
	LengthSeconds   int32                `json:"lengthSeconds"`
	LiveNow         bool                 `json:"liveNow"`
	Paid            bool                 `json:"paid"`
	Premium         bool                 `json:"premium"`

	// Playlist fields
	PlaylistID        string `json:"playlistId,omitempty"`
	PlaylistThumbnail string `json:"playlistThumbnail,omitempty"`
	AuthorVerified    bool   `json:"authorVerified,omitempty"`
	VideoCount        int32  `json:"videoCount,omitempty"`

	// Channel fields
	SubCount      int32 `json:"subCount,omitempty"`
	AutoGenerated bool  `json:"autoGenerated,omitempty"`

	// Hashtag fields
	URL          string `json:"url,omitempty"`
	ChannelCount int32  `json:"channelCount,omitempty"`
}

type InvidiousThumbnail struct {
	Quality string `json:"quality"`
	URL     string `json:"url"`
	Width   int32  `json:"width"`
	Height  int32  `json:"height"`
}

// GET /api/v1/search/suggestions.
type InvidiousSuggestionsResponse struct {
	Query       string   `json:"query"`
	Suggestions []string `json:"suggestions"`
}

// GET /api/v1/hashtag/:tag.
type InvidiousHashtagResponse struct {
	Results []InvidiousSearchResultItem `json:"results"`
}
